import type { ReactNode } from "react";
import { motion, useReducedMotion } from "motion/react";

/**
 * Entry reveal for section content. The motion is here to sequence a section
 * as the reader arrives at it; anything that does not benefit from sequencing
 * should render plainly instead of being wrapped.
 */
export function Reveal({
  children,
  delay = 0,
  className,
}: {
  children: ReactNode;
  delay?: number;
  className?: string;
}) {
  const reduce = useReducedMotion();

  return (
    <motion.div
      className={className}
      initial={reduce ? false : { opacity: 0, y: 24 }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true, amount: 0.2 }}
      transition={{ duration: 0.6, delay, ease: [0.16, 1, 0.3, 1] }}
    >
      {children}
    </motion.div>
  );
}
